export function getTopicsFor(subject: string, grade: string): string[] {
  const subjData = CURRICULUM_DATA[subject];
  if (!subjData) {
    return [
      `${subject} üzrə baza anlayışlar`,
      `${subject} üzrə nəzəri qanunauyğunluqlar`,
      `${subject} üzrə praktiki məsələlər və tətbiqlər`,
      `${subject} üzrə ümumiləşdirici təkrar`
    ];
  }

  // Exact grade match
  if (subjData[grade]) {
    return subjData[grade];
  }

  // Match partial keys like '5-8-ci siniflər' or '10-11-ci sinif'
  const gradeNum = parseInt(grade.replace(/[^0-9]/g, '')) || 0;
  for (const [rangeKey, topics] of Object.entries(subjData)) {
    if (rangeKey.includes(grade)) return topics;
    if (rangeKey.includes('-')) {
      const nums = rangeKey.match(/\d+/g)?.map(Number);
      if (nums && nums.length >= 2) {
        if (gradeNum >= nums[0] && gradeNum <= nums[nums.length - 1]) {
          return topics;
        }
      }
    }
  }

  // Default to first available grade's topics
  const firstKey = Object.keys(subjData)[0];
  return subjData[firstKey] || [];
}
